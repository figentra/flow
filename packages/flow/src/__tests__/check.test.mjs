/**
 * Figentra Flow file contract:
 * Purpose: hold `fflow check` to STA-1945 FR-1 and FR-3: it writes nothing; a synced repository passes; it fails,
 *   naming each cause, on any byte changed in an owned file (in the header, in the body, the header removed, or a
 *   strict JSON file with no header), a missing owned file, a preset that differs from the locked digest, an
 *   unreadable lock, an invalid config, a committed machine-only skill (FR-8) and a git that cannot list the
 *   tracked files (it fails closed); it warns from 14 days before an override's review date, fails after it, fails on
 *   a mandatory policy that is off, and on an override changed without a sync (FR-2, FR-4, FR-5); against Flow's
 *   records it fails on a task ticked `[x]` by hand and on a task in progress whose documents changed since it started,
 *   naming the task and `fflow task start` (FR-23, T024); an approval is bound to its documents' content, so an edit
 *   fails naming the stage to approve again while a status move does not, and a new approval clears it (A-3, T048).
 * Boundary: temporary folders and scratch git repositories; no network.
 * Runtime: node
 * Governing contract: ADR 0022; STA-1945.
 */
// @covers sta-1945:FR-1 sta-1945:FR-3 sta-1945:AC-1 sta-1945:P-001 sta-1945:P-005
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import { check, report } from "../commands/check.mjs";
import { sync } from "../commands/sync.mjs";
import { docsDigest } from "../commands/task.mjs";
import { LOCK } from "../lib/flow-dir.mjs";
import { digestOf, readLock, writeLock } from "../lib/lock.mjs";
import { approvalDigest, bindApprovals, docsIn, readRecord, updateRecord } from "../lib/record.mjs";
import { THIRD_PARTY } from "../lib/skills.mjs";
import { changePreset, governed, OWN_PRESET, snapshot } from "./__fixtures__/governed.mjs";

const quiet = { log: () => {} };
const SKILL = ".claude/skills/flow-plan/SKILL.md";

/**
 * The problems `check` finds, after proving it wrote nothing.
 * @param {string} root
 */
const problems = (root) => {
  const before = snapshot(root);
  const found = check(root).problems;
  assert.deepEqual(snapshot(root), before, "check writes nothing");
  return found.join("\n");
};

test("check: a synced repository passes and exits 0", (t) => {
  const root = governed(t);
  sync(root, { ...quiet, direct: true });
  assert.equal(problems(root), "");
  /** @type {string[]} */
  const lines = [];
  assert.deepEqual(report(root, [], { log: (l) => lines.push(l), quiet: false }), {
    code: 0,
    line: "ok",
  });
  assert.deepEqual(lines, ["fflow check: ok"]);
});

// @covers sta-1945:FR-2 sta-1945:FR-4
test("check: an override added or changed without a sync fails until the next sync", (t) => {
  const root = governed(t);
  sync(root, { ...quiet, direct: true });
  const owner = join(root, ".flow/overrides/policies/owner.yml");
  mkdirSync(dirname(owner), { recursive: true });
  writeFileSync(owner, 'kind: extend\ntarget: owner-only\nitems:\n  - "deploy/**"\n');
  assert.equal(
    problems(root),
    ".flow/overrides/ differs from what .flow/lock.json records (run `fflow sync`)",
  );
  sync(root, { ...quiet, direct: true });
  assert.equal(problems(root), "");
});

test("check: any byte changed in an owned file fails, header or no header", (t) => {
  const root = governed(t);
  sync(root, { ...quiet, direct: true });
  const file = join(root, SKILL);
  const text = readFileSync(file, "utf8");
  const edits = [
    text.replace("Generated by fflow", "Generated by hand"),
    text.replace(/\n# Generated by fflow[^\n]*/, ""),
    `${text} `,
  ];
  for (const edit of edits) {
    writeFileSync(file, edit);
    assert.match(problems(root), /flow-plan\/SKILL\.md differs from what `fflow sync` rendered/);
  }
  writeFileSync(file, text);
  assert.equal(problems(root), "");
  // A strict JSON output carries no header; its digest alone finds the edit.
  writeFileSync(join(root, ".claude/settings.json"), '{ "a": 1 }\n');
  const lock = /** @type {import("../lib/lock.mjs").Lock} */ (readLock(root));
  lock.files[".claude/settings.json"] = digestOf('{ "a": 1 }\n');
  writeLock(root, lock);
  assert.equal(problems(root), "");
  writeFileSync(join(root, ".claude/settings.json"), '{ "a": 2 }\n');
  assert.match(problems(root), /\.claude\/settings\.json differs/);
  rmSync(join(root, ".claude/settings.json"));
  assert.match(problems(root), /\.claude\/settings\.json is missing/);
});

test("check: names a preset that differs from the lock, an unreadable lock and an invalid config", (t) => {
  const root = governed(t, { own: true });
  sync(root, quiet);
  changePreset(root);
  assert.match(problems(root), /differs from .*records \(run `fflow update` to adopt it\)/);
  /** @type {string[]} */
  const lines = [];
  const r = report(root, [], { log: (l) => lines.push(l), quiet: false });
  assert.equal(r.code, 1);
  assert.match(r.line, /^1 problem\(s\): the installed/);
  writeFileSync(join(root, LOCK), "{ broken");
  assert.match(problems(root), /\.flow\/lock\.json is not valid JSON \(run `fflow sync`\)/);
  writeFileSync(join(root, "flow.config.json"), JSON.stringify({ version: 1, nope: true }));
  assert.match(problems(root), /flow\.config\.json: nope: is not a known key/);
});

test("check: names a lock it cannot read and a missing preset folder, without a stack trace", (t) => {
  const root = governed(t, { own: true });
  sync(root, quiet);
  writeFileSync(join(root, LOCK), JSON.stringify({ lockVersion: 2 }));
  assert.match(problems(root), /\.flow\/lock\.json is not a valid v2 lock: flow is not a string/);
  writeFileSync(join(root, LOCK), JSON.stringify({ lockVersion: 3 }));
  assert.match(problems(root), /lockVersion 3; this fflow reads 1 and 2/);
  rmSync(join(root, LOCK));
  sync(root, quiet);
  rmSync(join(root, OWN_PRESET), { recursive: true });
  assert.match(
    problems(root),
    /the preset flow\.config\.json names has no folder at .*presets\/ours/,
  );
});

// @covers sta-1945:FR-8 sta-1945:AC-10 sta-1945:P-013
test("check: refuses a committed machine-only skill, naming its source; an untracked copy is the machine's", (t) => {
  const root = governed(t, { own: true });
  spawnSync("git", ["init", "-q"], { cwd: root });
  writeFileSync(
    join(root, OWN_PRESET, THIRD_PARTY),
    'skills:\n  - id: animate\n    source: "the owner\'s library"\n    licence: own\n    machineOnly: true\n',
  );
  sync(root, quiet);
  const dir = ".claude/skills/animate";
  mkdirSync(join(root, dir), { recursive: true });
  writeFileSync(join(root, dir, "SKILL.md"), "---\nname: animate\n---\n");
  assert.equal(problems(root), "");
  spawnSync("git", ["add", dir], { cwd: root });
  assert.match(
    problems(root),
    /^\.claude\/skills\/animate is the machine-only skill animate, .*install it on the machine from the owner's library/,
  );
  // An invalid config is its own problem; the preset it names is not read for machine-only skills.
  const config = join(root, "flow.config.json");
  const valid = readFileSync(config, "utf8");
  writeFileSync(config, JSON.stringify({ ...JSON.parse(valid), bogus: true }));
  const invalid = problems(root);
  assert.match(invalid, /flow\.config\.json/);
  assert.doesNotMatch(invalid, /machine-only/);
  writeFileSync(config, valid);
  writeFileSync(join(root, OWN_PRESET, THIRD_PARTY), "skills: nope\n");
  assert.match(problems(root), /third-party\.yml: `skills` is not a list/);
});

// @covers sta-1945:FR-8
test("check: fails closed when git cannot list the tracked files of a preset with machine-only skills", (t) => {
  const root = governed(t, { own: true });
  writeFileSync(
    join(root, OWN_PRESET, THIRD_PARTY),
    'skills:\n  - id: animate\n    source: "the owner\'s library"\n    licence: own\n    machineOnly: true\n',
  );
  sync(root, quiet);
  // Not a git repository: no listing is not the same as no machine-only skill committed.
  assert.match(problems(root), /could not list the tracked SKILL\.md files: /);
});

// @covers sta-1945:FR-4 sta-1945:FR-5 sta-1945:AC-1 sta-1945:AC-4 sta-1945:P-007
test("check: warns from 14 days before an override's review date, fails after it, and fails on a policy that is off", (t) => {
  const root = governed(t);
  const off = join(root, ".flow/overrides/agents/ci.yml");
  mkdirSync(dirname(off), { recursive: true });
  writeFileSync(
    off,
    "kind: disable\ntarget: .claude/agents/ci-steward.md\nreason: r\nowner: o\nreview: 2027-01-31\n",
  );
  sync(root, { ...quiet, direct: true });
  const before = snapshot(root);
  assert.deepEqual(check(root, new Date("2027-01-16T00:00:00Z")), { problems: [], warnings: [] });
  assert.deepEqual(check(root, new Date("2027-01-17T00:00:00Z")), {
    problems: [],
    warnings: [".flow/overrides/agents/ci.yml: its review date 2027-01-31 is within 14 days"],
  });
  assert.deepEqual(check(root, new Date("2027-02-01T00:00:00Z")).problems, [
    ".flow/overrides/agents/ci.yml: its review date 2027-01-31 has passed (review it, then move `review` on or remove the override)",
  ]);
  assert.deepEqual(snapshot(root), before, "check writes nothing");
  writeFileSync(
    join(root, ".flow/overrides/agents/less.yml"),
    'kind: extend\ntarget: owner-only\nitems:\n  - "!.gitleaks.toml"\n',
  );
  assert.match(
    problems(root),
    /agents\/less\.yml: extend owner-only is refused: the mandatory policy owner-only cannot drop a rule \(!\.gitleaks\.toml\)/,
  );
});

// @covers sta-1945:FR-23 sta-1945:AC-22 sta-1945:AC-24 sta-1945:P-028
test("check: a hand tick and a task whose documents changed since its start fail, each named with its fix", (t) => {
  const root = governed(t);
  sync(root, { ...quiet, direct: true });
  const dir = join(root, ".agents/specs/sta-7-x");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "spec.md"), "# x\n\n**Status**: Implementing\n");
  writeFileSync(join(dir, "plan.md"), "# plan\n");
  const tasks = (/** @type {string} */ two) =>
    `# Tasks\n\n- [x] T001 One in \`a.mjs\`\n- [${two}] T002 Two in \`b.mjs\`\n- [-] T003 Three in \`c.mjs\`\n`;
  writeFileSync(join(dir, "tasks.md"), tasks(" "));
  const at = "2026-11-04T09:00:00.000Z";
  const head = "a".repeat(40);
  updateRecord(root, "sta-7", (r) => ({
    ...r,
    tasks: { T001: [{ command: "true", exit: 0, head, clean: true, digest: "sha256:0", at }] },
    started: { T003: { at, head, docs: docsDigest(dir) } },
  }));
  assert.equal(problems(root), "", "T001 has its evidence, T003 its documents");
  writeFileSync(join(dir, "tasks.md"), tasks("x"));
  writeFileSync(join(dir, "plan.md"), "# plan, amended\n");
  assert.deepEqual(problems(root).split("\n"), [
    ".agents/specs/sta-7-x/tasks.md: T002 is ticked [x] with no passing evidence in the record (`fflow task start STA-7 T002`, then `fflow task done STA-7 T002 --command <check>`)",
    `.agents/specs/sta-7-x: the spec, plan or tasks changed since T003 started (${at}); \`fflow task start STA-7 T003\` resets and restarts it`,
  ]);
  writeFileSync(join(root, ".flow/record/sta-7.json"), "{}");
  assert.match(problems(root), /sta-7\.json: .*is required/);
});

// @covers sta-1945:FR-30 sta-1945:AC-34 sta-1945:P-034
test("check: an approval binds its documents; an edit fails naming the stage, a status move does not", (t) => {
  const root = governed(t);
  sync(root, { ...quiet, direct: true });
  const dir = join(root, ".agents/specs/sta-8-x");
  mkdirSync(dir, { recursive: true });
  const history =
    "## Status history\n\n- 2026-11-03: Clarified → Planned — Approved by owner 2026-11-03\n";
  writeFileSync(join(dir, "spec.md"), `# x\n\n**Status**: Planned\n\nThe body.\n\n${history}`);
  writeFileSync(join(dir, "plan.md"), "# plan\n");
  updateRecord(root, "sta-8", (r) => bindApprovals(r, docsIn(dir)));
  assert.deepEqual(readRecord(root, "sta-8")?.approvals, [
    {
      who: "owner",
      when: "2026-11-03",
      stage: "planned",
      digest: approvalDigest("planned", docsIn(dir)),
    },
  ]);
  assert.equal(problems(root), "");
  // moving the status on changes nothing approved
  writeFileSync(
    join(dir, "spec.md"),
    `# x\n\n**Status**: Tasked\n\nThe body.\n\n${history}- 2026-11-04: Planned → Tasked\n`,
  );
  assert.equal(problems(root), "");
  writeFileSync(join(dir, "plan.md"), "# plan, edited\n");
  assert.equal(
    problems(root),
    '.agents/specs/sta-8-x: spec.md and plan.md changed since the planned approval (owner 2026-11-03): the stage is back at approval; approve it again ("Approved by <who> <YYYY-MM-DD>" on the planned stage)',
  );
  // a new approval is of the documents as they are: no longer stale, and the next stage binds it
  writeFileSync(
    join(dir, "spec.md"),
    `# x\n\n**Status**: Tasked\n\nThe body.\n\n${history}- 2026-11-04: Planned → Tasked\n- 2026-11-05: Tasked → Planned — Approved by owner 2026-11-05\n`,
  );
  assert.equal(problems(root), "");
  updateRecord(root, "sta-8", (r) => bindApprovals(r, docsIn(dir)));
  assert.equal(readRecord(root, "sta-8")?.approvals.length, 2);
  assert.equal(problems(root), "");
});
