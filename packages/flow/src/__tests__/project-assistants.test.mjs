/**
 * Figentra Flow file contract:
 * Purpose: hold `projectAssistants` (STA-2098 H6) to its contract: an agent becomes a Claude Code agent (its tier's
 *   model, its tools) and an OpenCode agent (its mode, its tier's model, a deny for every action its tools do not
 *   reach), each naming its source; an agent whose tier an assistant does not map, or whose `assistants` leave it out,
 *   is not projected there; skills, hooks and templates are linked; the reviewer list and `.mcp.json` are rendered; a
 *   stale generated agent is pruned and a real file is never overwritten; `check` writes nothing and names the drift;
 *   an invalid agent is broken.
 * Boundary: temporary folders only; no git, no network.
 * Runtime: node
 * Governing contract: STA-2098 (H6).
 * Secrets: none.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import {
  existsSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

import { projectAssistants } from "../lib/project-assistants.mjs";

/** A folder with `files` written into it and `.claude/` and `.opencode/` present. */
function tree(/** @type {Record<string, string>} */ files) {
  const root = mkdtempSync(join(tmpdir(), "flow-project-"));
  for (const dir of [".claude", ".opencode"]) mkdirSync(join(root, dir));
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

const MODELS = `tiers: [steward, reviewer, lead]
assistants:
  claude:
    steward: haiku
    reviewer: sonnet
    lead: opus
  opencode:
    steward: amazon-bedrock/kimi
`;

const REVIEWER = `---
# Generated by fflow from the stackra preset: do not edit.
name: code-reviewer
description: Reviews a diff.
tier: reviewer
reviewer: true
tools: [Read, Grep, Bash]
---

# code-reviewer

Reviews.
`;

const STEWARD = `---
name: git-steward
description: "Keeps the trees clean"
tier: steward
---

Cleans.
`;

const BASE = {
  ".agents/models.yaml": MODELS,
  ".agents/agents/code-reviewer.md": REVIEWER,
  ".agents/agents/git-steward.md": STEWARD,
  ".agents/agents/README.md": "# not an agent\n",
  ".agents/skills/tdd/SKILL.md": "# tdd\n",
  ".agents/hooks/guard.mjs": "export {};\n",
  ".agents/templates/spec.md": "# spec\n",
  ".mcp.yaml": "mcpServers:\n  stackra:\n    command: node\n    args: [mcp.mjs]\n",
};

test("projects each agent in each assistant's dialect, links the shared kinds and renders the reviewer list and .mcp.json", (t) => {
  const root = tree(BASE);
  t.after(() => rmSync(root, { recursive: true }));
  const out = projectAssistants(root);
  assert.deepEqual([out.conflict, out.broken], [[], []]);

  const claude = readFileSync(join(root, ".claude/agents/code-reviewer.md"), "utf8");
  assert.ok(
    claude.startsWith(
      '---\nname: code-reviewer\ndescription: "Reviews a diff."\ntools: Read, Grep, Bash\nmodel: sonnet\n---\n\n' +
        "<!-- generated from .agents/agents/code-reviewer.md by fflow sync — edit the source, not this file -->\n\n# code-reviewer",
    ),
    claude,
  );
  // OpenCode maps no reviewer tier, so the reviewer goes to Claude Code only; the steward goes to both.
  assert.equal(existsSync(join(root, ".opencode/agents/code-reviewer.md")), false);
  const opencode = readFileSync(join(root, ".opencode/agents/git-steward.md"), "utf8");
  assert.match(
    opencode,
    /^---\ndescription: "Keeps the trees clean"\nmode: subagent\nmodel: "amazon-bedrock\/kimi"\n---/,
  );
  assert.match(
    readFileSync(join(root, ".claude/agents/git-steward.md"), "utf8"),
    /^model: haiku$/m,
  );
  assert.equal(existsSync(join(root, ".claude/agents/README.md")), false);

  for (const rel of [
    ".claude/skills/tdd",
    ".claude/hooks/guard.mjs",
    ".claude/templates/spec.md",
    ".opencode/templates/spec.md",
  ])
    assert.ok(lstatSync(join(root, rel)).isSymbolicLink(), rel);
  assert.equal(
    existsSync(join(root, ".opencode/skills")),
    false,
    "OpenCode reads .agents/skills itself",
  );

  assert.match(
    readFileSync(join(root, ".agents/hooks/_reviewer-agents.mjs"), "utf8"),
    /^export const REVIEWER_AGENTS = new Set\(\["code-reviewer"\]\);$/m,
  );
  assert.deepEqual(JSON.parse(readFileSync(join(root, ".mcp.json"), "utf8")), {
    mcpServers: { stackra: { command: "node", args: ["mcp.mjs"] } },
  });

  // A second run changes nothing, and `check` finds nothing.
  assert.deepEqual(projectAssistants(root).written, []);
  assert.deepEqual(projectAssistants(root, { check: true }).drift, []);
});

test("derives OpenCode denies from an agent's tools, and an agent's own permissions win", (t) => {
  const root = tree({
    ".agents/models.yaml": MODELS,
    ".agents/agents/reader.md":
      "---\ndescription: Reads.\ntier: steward\ntools: [Read, Grep]\n---\nBody.\n",
  });
  t.after(() => rmSync(root, { recursive: true }));
  projectAssistants(root);
  const text = readFileSync(join(root, ".opencode/agents/reader.md"), "utf8");
  for (const action of ["edit", "shell", "webfetch", "websearch", "subagent"])
    assert.match(
      text,
      new RegExp(`- action: "${action}"\\n    resource: "\\*"\\n    effect: deny`),
      action,
    );
});

test("check writes nothing and names the drift; a stale generated agent is pruned; a real file is a conflict", (t) => {
  const root = tree(BASE);
  t.after(() => rmSync(root, { recursive: true }));
  const missing = projectAssistants(root, { check: true });
  assert.ok(missing.drift.includes(".claude/agents/code-reviewer.md: missing"));
  assert.equal(existsSync(join(root, ".claude/agents/code-reviewer.md")), false);
  // A fresh clone has no .mcp.json, which is not drift.
  assert.ok(!missing.drift.some((d) => d.startsWith(".mcp.json")));

  projectAssistants(root);
  rmSync(join(root, ".agents/agents/git-steward.md"));
  assert.ok(
    projectAssistants(root, { check: true }).drift.some((d) =>
      d.startsWith(".claude/agents/git-steward.md: stale"),
    ),
  );
  assert.ok(projectAssistants(root).pruned.includes(".claude/agents/git-steward.md"));
  assert.equal(existsSync(join(root, ".claude/agents/git-steward.md")), false);

  writeFileSync(join(root, ".claude/agents/code-reviewer.md"), "# my own agent\n");
  const out = projectAssistants(root);
  assert.ok(out.conflict.some((c) => c.startsWith(".claude/agents/code-reviewer.md")));
  assert.equal(
    readFileSync(join(root, ".claude/agents/code-reviewer.md"), "utf8"),
    "# my own agent\n",
  );
});

test("an invalid agent or models file is broken, never skipped", (t) => {
  const root = tree({
    ".agents/models.yaml": MODELS,
    ".agents/agents/odd.md": "---\ndescription: Odd.\ncolour: blue\ntier: wizard\n---\nBody.\n",
  });
  t.after(() => rmSync(root, { recursive: true }));
  const [broken] = projectAssistants(root).broken;
  assert.match(broken, /odd\.md: unknown key 'colour'; 'tier' is 'wizard'/);
  writeFileSync(
    join(root, ".agents/models.yaml"),
    "tiers: [steward]\nassistants:\n  claude:\n    steward: haiku\n",
  );
  assert.match(projectAssistants(root).broken[0], /'assistants.opencode' is missing/);
});
